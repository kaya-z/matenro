"""Assemble the guest shims and write them as a09 `fcb` data (included by cpm.asm).

  python3 os9/cpm/mkshims.py OUT.inc
"""
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'tools'))
import z80asm


def fcb(label, data):
    lines = ['%-8s equ *' % label]
    for i in range(0, len(data), 16):
        lines.append('         fcb ' + ','.join('$%02X' % b for b in data[i:i + 16]))
    lines.append('%sn equ *-%s' % (label, label))
    return '\n'.join(lines)


def main():
    out = sys.argv[1]
    base, z = z80asm.assemble(open(os.path.join(HERE, 'z80shim.asm'), encoding='utf-8').read())
    assert base == 0xFC00, hex(base)
    with tempfile.TemporaryDirectory() as t:
        b = os.path.join(t, 'i88.bin')
        subprocess.run(['nasm', '-f', 'bin', os.path.join(HERE, 'i8088shim.asm'), '-o', b], check=True)
        i88 = open(b, 'rb').read()
    text = ['* generated by os9/cpm/mkshims.py - do not edit',
            fcb('z80shim', z), fcb('i88shim', i88),
            fcb('i88rst', bytes([0xEA, 0x40, 0x05, 0x00, 0x00]))]       # JMP FAR 0000:0540 at FFFF0
    open(out, 'w', encoding='utf-8').write('\n'.join(text) + '\n')


if __name__ == '__main__':
    main()
