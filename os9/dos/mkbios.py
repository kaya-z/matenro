"""Assemble the BIOS of MS-DOS (bios88.asm) and write it as a09 `fcb` data (included by dos.asm).

  python3 os9/dos/mkbios.py OUT.inc
"""
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    with tempfile.TemporaryDirectory() as t:
        b = os.path.join(t, 'bios.bin')
        subprocess.run(['nasm', '-f', 'bin', os.path.join(HERE, 'bios88.asm'), '-o', b], check=True)
        data = open(b, 'rb').read()
    assert len(data) == 0x500, len(data)
    lines = ['* generated by os9/dos/mkbios.py - do not edit', 'bios     equ *']
    for i in range(0, len(data), 16):
        lines.append('         fcb ' + ','.join('$%02X' % x for x in data[i:i + 16]))
    lines.append('biosn    equ *-bios')
    open(sys.argv[1], 'w', encoding='utf-8').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
