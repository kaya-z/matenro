"""mkfont.py FONT8X16.HEX OUT.inc - the glyphs of ASCII $20-$7E (95 characters x 16 lines) of the 8x16 font of the HDMI screen (Shinonome, public domain:
sim09 fpga/tn9k/rtl/font8x16.hex, 256 characters x 16 bytes, the left dot is bit 7) as a09 `fcb` lines for os9/gfx/gfx.asm."""
import sys
font = [int(x, 16) for x in open(sys.argv[1]).read().split()]
lines = ['* generated by os9/gfx/mkfont.py - do not edit', 'gfont    equ *']
for ch in range(32, 127):
    lines.append('         fcb ' + ','.join('$%02X' % font[ch * 16 + r] for r in range(16)) + '         ' + ('%02X' % ch))
open(sys.argv[2], 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
